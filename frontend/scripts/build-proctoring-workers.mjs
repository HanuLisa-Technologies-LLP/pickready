#!/usr/bin/env node
/**
 * Bundle the two proctoring inference workers into `public/proctoring/`.
 *
 * WHY THIS SCRIPT EXISTS RATHER THAN A BUNDLER FEATURE. The idiomatic form,
 * `new Worker(new URL("./worker.ts", import.meta.url))`, is compiled into a
 * worker chunk by webpack, and Next 16 builds with Turbopack, which resolves
 * that URL as a STATIC ASSET instead: measured on this repo, the build copied
 * `cv.worker.ts` verbatim into `.next/static/media/` and the browser would
 * have been served untranspiled TypeScript. That is a silent failure at
 * runtime in a candidate's browser during an assessment, which is the worst
 * place for one, so the workers are built explicitly here and loaded by a
 * plain path.
 *
 * They are CLASSIC workers, not modules. `@mediapipe/tasks-vision` loads its
 * wasm glue with `importScripts`, which exists only in a classic worker; it
 * has a dynamic-import fallback, but the supported path is the one to be on.
 *
 * The output is a BUILD ARTIFACT and is gitignored. `prebuild` and `predev`
 * run this, so `npm run build` and `npm run dev` both produce it; nothing
 * generated by our own source is committed, because a committed bundle goes
 * stale against the source it was built from and nothing says so.
 */
import { mkdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const FRONTEND = join(here, "..");

/** Entry point to output file. `worker-client.ts` loads exactly these paths,
 *  and `lib/proctoring/model-assets.test.ts` reads this literal out of this
 *  source and asserts the two agree. */
const WORKER_BUNDLES = {
  "lib/proctoring/workers/cv.worker.ts": "public/proctoring/cv.worker.js",
  "lib/proctoring/workers/identity.worker.ts": "public/proctoring/identity.worker.js",
};

const outputDirectory = join(FRONTEND, "public", "proctoring");

async function main() {
  rmSync(outputDirectory, { recursive: true, force: true });
  mkdirSync(outputDirectory, { recursive: true });
  for (const [entry, output] of Object.entries(WORKER_BUNDLES)) {
    const result = await build({
      entryPoints: [join(FRONTEND, entry)],
      outfile: join(FRONTEND, output),
      bundle: true,
      format: "iife",
      platform: "browser",
      target: "es2020",
      // The worker is shipped to a candidate's browser and is part of the
      // measure that raises the effort of interfering with monitoring
      // (proctoring spec section 9). It raises the effort; it does not stop a
      // determined reader, and nothing here pretends otherwise.
      minify: true,
      sourcemap: false,
      legalComments: "none",
      logLevel: "warning",
      define: { "process.env.NODE_ENV": '"production"' },
    });
    if (result.errors.length > 0) {
      throw new Error(`${entry}: ${result.errors.length} bundling errors`);
    }
    process.stdout.write(`  ${output}\n`);
  }
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
